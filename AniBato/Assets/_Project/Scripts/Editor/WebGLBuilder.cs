using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;
namespace AniBato.EditorTools
{
    public static class WebGLBuilder
    {
        [MenuItem("あにバト/WebGLをビルド")]
        public static void Build()
        {
            if(EditorUserBuildSettings.activeBuildTarget!=BuildTarget.WebGL)throw new InvalidOperationException("-buildTarget WebGL で起動してください。");
            const string template="Assets/WebGLTemplates/AniBato";
            Directory.CreateDirectory(template);File.Copy("../tools/webgl/index.html",template+"/index.html",true);
            const string font="Assets/_Project/Resources/NotoSansJP-Regular.otf";
            Directory.CreateDirectory(Path.GetDirectoryName(font));
            if(!File.Exists(font))File.Copy("../art_source/fonts/NotoSansJP-Regular.otf",font);
            AssetDatabase.Refresh();
            PlayerSettings.WebGL.template="PROJECT:AniBato";
            PlayerSettings.WebGL.compressionFormat=WebGLCompressionFormat.Gzip;
            PlayerSettings.WebGL.decompressionFallback=true;PlayerSettings.WebGL.dataCaching=true;
            // Full-resolution roster artwork must fit alongside the startup data archive.
            // Grow on demand instead of reserving the maximum at startup.
            PlayerSettings.WebGL.initialMemorySize=512;PlayerSettings.WebGL.maximumMemorySize=4096;
            PlayerSettings.WebGL.memoryGrowthMode=WebGLMemoryGrowthMode.Geometric;
            PlayerSettings.WebGL.nameFilesAsHashes=true;
            PlayerSettings.SetScriptingBackend(UnityEditor.Build.NamedBuildTarget.WebGL,ScriptingImplementation.IL2CPP);
            EditorUserBuildSettings.webGLBuildSubtarget=WebGLTextureSubtarget.DXT;
            WebGLSpritePacking.Prepare();
            AssetDatabase.SaveAssets();
            const string output="../Build/WebGL";
            // Discard only hash-named files generated by earlier attempts in this exact build folder.
            string buildFiles=Path.GetFullPath(output+"/Build");
            string allowed=Path.Combine(Path.GetFullPath(".."),"Build","WebGL","Build");
            if(buildFiles!=allowed)throw new InvalidOperationException("Unsafe WebGL output folder");
            if(Directory.Exists(buildFiles))foreach(string file in Directory.GetFiles(buildFiles))
                if(System.Text.RegularExpressions.Regex.IsMatch(Path.GetFileName(file),"^[a-f0-9]{32}\\.(data|wasm|framework\\.js|loader\\.js)(\\.unityweb)?$"))File.Delete(file);
            var report=BuildPipeline.BuildPlayer(new BuildPlayerOptions{
                scenes=EditorBuildSettings.scenes.Where(s=>s.enabled).Select(s=>s.path).ToArray(),
                locationPathName=output,target=BuildTarget.WebGL,options=BuildOptions.DetailedBuildReport
            });
            if(report.summary.result!=BuildResult.Succeeded)throw new InvalidOperationException("WebGLビルド失敗: "+report.summary.result);
            File.Copy("../art_source/fonts/OFL-NotoCJK.txt",output+"/ThirdPartyNotices.txt",true);
            var files=Directory.GetFiles(output,"*",SearchOption.AllDirectories).Select(p=>new FileInfo(p)).ToArray();
            string json=JsonUtility.ToJson(new Result{result="success",bytes=files.Sum(f=>f.Length),seconds=report.summary.totalTime.TotalSeconds,files=files.Length},true);
            File.WriteAllText("../TestResults/webgl-build.json",json);Debug.Log("WEBGL_REPORT "+json);
        }
        [Serializable] private sealed class Result { public string result;public long bytes;public double seconds;public int files; }
    }
}
